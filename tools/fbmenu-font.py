#!/usr/bin/env python3
"""Build a tiny antialiased font subset; Pillow is only needed at build time."""
from pathlib import Path
import sys
from PIL import Image, ImageDraw, ImageFont

font=ImageFont.truetype(sys.argv[1],16)
glyphs=[]
data=bytearray()
# Latin and extended Latin cover boot labels; UTF-8 decoding stays in the renderer.
for code in [*range(32,127),*range(160,384)]:
    char=chr(code)
    left,top,right,bottom=font.getbbox(char)
    width,height=right-left,bottom-top
    image=Image.new('L',(max(width,1),max(height,1)))
    ImageDraw.Draw(image).text((-left,-top),char,font=font,fill=255)
    glyphs.append((code,len(data),width,height,round(font.getlength(char)),left,top))
    # Store runs of 1..16 pixels with four bits of antialias coverage.
    values=[round(value/17) for value in image.tobytes()] if width*height else []
    i=0
    while i<len(values):
        length=1
        while length<16 and i+length<len(values) and values[i+length]==values[i]:
            length+=1
        data.append(((length-1)<<4)|values[i])
        i+=length

with Path(__file__).with_name('fbmenu-font.h').open('w',encoding='utf-8',newline='\n') as output:
    output.write('/* Generated by fbmenu-font.py from DejaVu Sans; see fbmenu-font.LICENSE. */\n')
    output.write('struct glyph { uint16_t code; uint32_t offset; uint8_t width,height,advance; int8_t left,top; };\n')
    output.write('static const struct glyph font_glyphs[]={\n')
    for glyph in glyphs:
        output.write('   {'+','.join(map(str,glyph))+'},\n')
    output.write('};\nstatic const unsigned char font_pixels[]={\n')
    for i in range(0,len(data),24):
        output.write('   '+','.join(str(value) for value in data[i:i+24])+',\n')
    output.write('};\n')
